const variantColors = {
  1: ['Obsidian', 'Arctic Silver'],
  2: ['Infrared', 'Triple Black'],
  3: ['Sand / Black', 'Steel'],
  4: ['Silver / Black', 'All Black'],
  5: ['Midnight', 'Ghost White'],
  6: ['Space Gray', 'Silver'],
  7: ['All Black', 'Silver'],
  8: ['Graphite', 'Starlight'],
};

const createVariants = (id, color, sizes = []) => {
  const colors = variantColors[id];
  return sizes.flatMap((size) => colors.map((variantColor, index) => ({
    id: `${variantColor.toLowerCase().replace(/[^a-z0-9]+/g, '-')}-${size.toLowerCase()}`,
    color: variantColor,
    size,
    stock: [12, 6, 0, 4][(id + index + Number(size.replace(/\D/g, '') || 0)) % 4],
  })));
};

